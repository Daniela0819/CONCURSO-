# Escribe aquí tu código para descargar los datos de tus 3 activos elegidos
import yfinance as yf
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

ticker = "JPM,BAC,V,MA"

datos = yf.download(
    ticker,
    start="2021-01-01",
    end="2026-01-01",
    auto_adjust=False
)

datos.head()

import matplotlib.pyplot as plt

# 1. Filtra y extrae únicamente los precios de cierre (Close)
cierre = datos["Close"]

# 2. Grafica en una sola figura la evolución temporal de los precios originales de tus 3 activos
plt.figure(figsize=(12, 5))
plt.plot(cierre)
plt.title("Evolución temporal de precios originales")
plt.xlabel("Fecha")
plt.ylabel("Precio")
plt.legend(cierre.columns)  # Muestra el nombre de cada activo
plt.grid(True)
plt.show()

# 1. Calcular rendimientos
rendimiento = cierre.pct_change()
rendimiento.head()
print("Promedio:", rendimiento.mean())
print("Desviación estándar:", rendimiento.std())
print("Mínimo:", rendimiento.min())
print("Máximo:", rendimiento.max())

# 2. Histograma con el activo más volátil
import seaborn as sns
import matplotlib.pyplot as plt
activo_mas_volatil = rendimiento.std().idxmax()
plt.figure(figsize=(10, 5))
sns.histplot(
    rendimiento[activo_mas_volatil], kde=True, bins=30, color="skyblue"
)
plt.title(f"Distribución de rendimientos Diarios - {activo_mas_volatil}")
plt.xlabel("Rendimiento Diarios")
plt.ylabel("Frecuencia")
plt.grid(True)
plt.show()

# 3. Boxplot comparativo de rendimientos
plt.figure(figsize=(10, 6))
sns.boxplot(data=rendimiento)
plt.title("Comparación de Rendimientos Diarios (Boxplot)")
plt.xlabel("Activos")
plt.ylabel("Rendimiento Diario")
plt.grid(True)
plt.show()

import matplotlib.pyplot as plt
import seaborn as sns

# 1. Calcular matriz de correlación de Pearson
matriz_correlacion = rendimiento.corr(method="pearson")

# Mostrar la matriz en consola/notebook
print(matriz_correlacion)

# 2. Dibujar el Heatmap utilizando Seaborn
plt.figure(figsize=(8, 6))
sns.heatmap(
    matriz_correlacion,
    annot=True,  # Muestra los valores numéricos dentro de las celdas
    cmap="coolwarm",  # Paleta de colores (azul=negativo, rojo=positivo)
    vmin=-1,
    vmax=1,  # Escala de -1 a 1
    fmt=".2f",  # Formato de 2 decimales
    linewidths=0.5,
)
plt.title("Matriz de Correlación de Rendimiento Diarios")
plt.show()

